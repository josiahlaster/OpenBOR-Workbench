import { splitInlineComment, tokenizeLine } from './parser';
import type { ProjectEntity } from './types';

export interface ManifestEntry {
  command: 'load' | 'know';
  name: string;
  path: string;
  line: number;
  raw: string;
  comment: string | null;
}

export interface ParsedManifest {
  entries: ManifestEntry[];
  otherLines: number;
  duplicates: string[];
}

export function parseModelsManifest(text: string): ParsedManifest {
  const entries: ManifestEntry[] = [];
  const seen = new Set<string>();
  const duplicates: string[] = [];
  let otherLines = 0;
  text.split(/\r\n|\n|\r/).forEach((raw, line) => {
    const split = splitInlineComment(raw);
    const tokens = tokenizeLine(split.content.trim());
    if (tokens.length === 0) return;
    const command = tokens[0].toLowerCase();
    if (command === 'load' || command === 'know') {
      const name = tokens[1] ?? '';
      const path = tokens[2] ?? '';
      if (seen.has(name.toLowerCase())) duplicates.push(name);
      seen.add(name.toLowerCase());
      entries.push({
        command,
        name,
        path,
        line,
        raw,
        comment: split.comment,
      });
    } else {
      otherLines += 1;
    }
  });
  return { entries, otherLines, duplicates };
}

export function normalizeAssetPath(path: string): string {
  return path
    .replace(/\\/g, '/')
    .replace(/^\.?\//, '')
    .replace(/\/+/g, '/')
    .toLowerCase();
}

export function entityManifestPath(entity: Pick<ProjectEntity, 'fileName' | 'path'>): string {
  if (entity.path) return entity.path.replace(/\\/g, '/');
  return `data/chars/${entity.fileName.replace(/\.txt$/i, '')}/${entity.fileName}`;
}

export function generateModelsManifest(
  entities: ProjectEntity[],
  existing?: string | null,
): string {
  const header: string[] = [];
  if (existing) {
    for (const line of existing.split(/\r\n|\n|\r/)) {
      if (!/^\s*(load|know)\s/i.test(line)) header.push(line);
    }
  } else {
    header.push('# OpenBOR models.txt generated by OpenBOR Stats');
  }
  while (header.length > 0 && header[header.length - 1].trim() === '') header.pop();
  const seen = new Set<string>();
  const entries: string[] = [];
  for (const entity of entities) {
    const name =
      entity.summary.name?.trim() ||
      entity.fileName.replace(/\.txt$/i, '').replace(/[^\w-]/g, '_');
    if (seen.has(name.toLowerCase())) continue;
    seen.add(name.toLowerCase());
    entries.push(`load ${name} ${entityManifestPath(entity)}`);
  }
  return `${[...header, '', ...entries, ''].join('\n')}`;
}

export function findMissingManifestEntities(
  manifest: ParsedManifest,
  entities: ProjectEntity[],
): { name: string; path: string; line: number }[] {
  const byName = new Set(
    entities.map((entity) => (entity.summary.name ?? '').toLowerCase()).filter(Boolean),
  );
  const byPath = new Set(
    entities.flatMap((entity) => [
      normalizeAssetPath(entity.path),
      normalizeAssetPath(entity.fileName),
    ]),
  );
  return manifest.entries
    .filter((entry) => {
      if (!entry.name) return true;
      if (byName.has(entry.name.toLowerCase())) return false;
      if (byPath.has(normalizeAssetPath(entry.path))) return false;
      return true;
    })
    .map((entry) => ({ name: entry.name, path: entry.path, line: entry.line + 1 }));
}
