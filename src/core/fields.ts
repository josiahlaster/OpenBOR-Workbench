const int = (
  name: string,
  label: string,
  opts: Partial<HeaderArgSpec> = {},
): HeaderArgSpec => ({ name, label, kind: 'integer', ...opts });
const float = (
  name: string,
  label: string,
  opts: Partial<HeaderArgSpec> = {},
): HeaderArgSpec => ({ name, label, kind: 'float', ...opts });
const text = (
  name: string,
  label: string,
  opts: Partial<HeaderArgSpec> = {},
): HeaderArgSpec => ({ name, label, kind: 'text', ...opts });
const bool = (
  name: string,
  label: string,
  opts: Partial<HeaderArgSpec> = {},
): HeaderArgSpec => ({
  name,
  label,
  kind: 'integer',
  options: ['0', '1'],
  defaultValue: '0',
  ...opts,
});

