import { describe, expect, it } from 'vitest';
import {
  findMissingManifestEntities,
  generateModelsManifest,
  parseModelsManifest,
} from './modelsManifest';
import type { ProjectEntity } from './types';
import { buildSummary } from './summary';
import { bruteRaw, knightRaw, modelsRaw } from '../test/fixtures';

function entity(raw: string, fileName: string, path: string): ProjectEntity {
  return {
    id: fileName,
    fileName,
    path,
    raw,
    savedRaw: raw,
    createdAt: 1,
    updatedAt: 1,
    summary: buildSummary(raw),
    revisions: [],
  };
}

const knight = entity(knightRaw, 'knight.txt', 'data/chars/knight/knight.txt');
const brute = entity(bruteRaw, 'brute.txt', 'data/chars/brute/brute.txt');

describe('parseModelsManifest', () => {
  it('reads load and know entries with comments', () => {
    const parsed = parseModelsManifest(modelsRaw);
    expect(parsed.entries).toHaveLength(2);
    expect(parsed.entries[0]).toMatchObject({
      command: 'load',
      name: 'Knight',
      path: 'data/chars/knight/knight.txt',
      line: 3,
    });
    expect(parsed.duplicates).toEqual([]);
  });

  it('detects duplicate registrations and unknown commands', () => {
    const text = 'load A data/a.txt\nload A data/a2.txt\nmusic data/theme.bor\n';
    const parsed = parseModelsManifest(text);
    expect(parsed.duplicates).toEqual(['A']);
    expect(parsed.otherLines).toBe(1);
    expect(parsed.entries[1].line).toBe(1);
  });
});

describe('generateModelsManifest', () => {
  it('keeps existing comments and replaces load lines', () => {
    const generated = generateModelsManifest([knight, brute], modelsRaw);
    expect(generated).toContain('# OpenBOR Stats fixture manifest');
    expect(generated).toContain('load Knight data/chars/knight/knight.txt');
    expect(generated).toContain('load Brute data/chars/brute/brute.txt');
    expect(generated.match(/^load /gm)).toHaveLength(2);
    expect(generated.endsWith('\n')).toBe(true);
    expect(parseModelsManifest(generated).entries).toHaveLength(2);
  });

  it('skips duplicate model names and falls back to the file name', () => {
    const nameless: ProjectEntity = {
      ...brute,
      id: 'nameless',
      fileName: 'nameless_model.txt',
      path: 'data/chars/nameless_model.txt',
      summary: { ...brute.summary, name: null },
    };
    const generated = generateModelsManifest([knight, knight, nameless], null);
    expect(generated.match(/^load /gm)).toHaveLength(2);
    expect(generated).toContain('load nameless_model data/chars/nameless_model.txt');
    expect(generated).toContain('# OpenBOR models.txt generated by OpenBOR Stats');
  });
});

describe('findMissingManifestEntities', () => {
  it('matches by model name or by path and reports the rest', () => {
    const manifest = parseModelsManifest(
      [
        'load Knight data/chars/knight/knight.txt',
        'load brute data/chars/elsewhere/brute.txt',
        'load Ghost data/chars/ghost/ghost.txt',
      ].join('\n'),
    );
    const missing = findMissingManifestEntities(manifest, [knight, brute]);
    expect(missing).toHaveLength(1);
    expect(missing[0]).toMatchObject({ name: 'Ghost', line: 3 });
  });
});
