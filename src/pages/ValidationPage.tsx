import {
  AlertCircle,
  AlertTriangle,
  Download,
  FileCode2,
  Info,
  ShieldCheck,
  Upload,
} from 'lucide-react';
import { useMemo, useState } from 'react';
import {
  Badge,
  Button,
  Card,
  EmptyState,
  PageHeader,
  SearchInput,
} from '../components/ui';
import type { ProjectEntity, ValidationFinding } from '../core/types';
import { downloadText, formatDate, typeLabel, typeTone } from '../lib/format';
import { navigate } from '../lib/router';
import { useApp } from '../state/AppStore';
import { useImport } from '../components/ImportDialog';

type SeverityFilter = 'all' | 'error' | 'warning' | 'info';

export function ValidationPage() {
  const { activeProject, validation } = useApp();
  const { openImport } = useImport();
  const [severity, setSeverity] = useState<SeverityFilter>('all');
  const [entityFilter, setEntityFilter] = useState('all');
  const [query, setQuery] = useState('');

  const findingsByEntity = useMemo(() => {
    if (!activeProject || !validation) return [];
    const term = query.trim().toLowerCase();
    return activeProject.entities
      .filter((entity) => entityFilter === 'all' || entity.id === entityFilter)
      .map((entity) => ({
        entity,
        findings: (validation.perEntity[entity.id] ?? []).filter(
          (finding) =>
            (severity === 'all' || finding.severity === severity) &&
            (!term ||
              finding.message.toLowerCase().includes(term) ||
              finding.code.toLowerCase().includes(term) ||
              (finding.animation ?? '').toLowerCase().includes(term)),
        ),
      }))
      .filter((entry) => entry.findings.length > 0);
  }, [activeProject, entityFilter, query, severity, validation]);

  if (!activeProject) {
    return (
      <>
        <PageHeader eyebrow="Analysis" title="Validation" subtitle="Engine-aware checks for OpenBOR model files." />
        <EmptyState
          icon={ShieldCheck}
          title="No active project"
          description="Select a project to validate its models."
          actions={<Button onClick={() => navigate('projects')}>Open projects</Button>}
        />
      </>
    );
  }

  if (!validation) {
    return (
      <EmptyState
        icon={ShieldCheck}
        title="Validation is not ready"
        description="The project is still loading, or its saved files could not be read."
      />
    );
  }

  const totalVisible =
    findingsByEntity.reduce((sum, entry) => sum + entry.findings.length, 0) +
    (entityFilter === 'all'
      ? validation.project.filter((finding) => severity === 'all' || finding.severity === severity).length
      : 0);

  const downloadReport = () => {
    const lines: string[] = [
      `# OpenBOR Stats validation report`,
      ``,
      `Project: ${activeProject.name}`,
      `Generated: ${formatDate(Date.now())}`,
      `Errors: ${validation.errors}`,
      `Warnings: ${validation.warnings}`,
      `Info: ${validation.infos}`,
      ``,
    ];
    if (validation.project.length > 0) {
      lines.push('## Project findings', '');
      for (const finding of validation.project) {
        lines.push(`- [${finding.severity.toUpperCase()}] ${finding.code}: ${finding.message}`);
        if (finding.detail) lines.push(`  - Detail: ${finding.detail}`);
        if (finding.fix) lines.push(`  - Fix: ${finding.fix}`);
      }
      lines.push('');
    }
    for (const entity of activeProject.entities) {
      const findings = validation.perEntity[entity.id] ?? [];
      if (findings.length === 0) continue;
      lines.push(`## ${entity.summary.name ?? entity.fileName}`, '');
      lines.push(`Path: ${entity.path}`, '');
      for (const finding of findings) {
        lines.push(
          `- [${finding.severity.toUpperCase()}] ${finding.code}${finding.line ? ` (line ${finding.line})` : ''}: ${finding.message}`,
        );
        if (finding.animation) lines.push(`  - Animation: ${finding.animation}${finding.frame ? `, frame ${finding.frame}` : ''}`);
        if (finding.detail) lines.push(`  - Detail: ${finding.detail}`);
        if (finding.fix) lines.push(`  - Fix: ${finding.fix}`);
      }
      lines.push('');
    }
    lines.push('Generated by OpenBOR Stats. Validation is limited to documented fields and imported assets; test exported files in OpenBOR.');
    downloadText(`${activeProject.name.replace(/[^\w-]+/g, '-')}-validation.md`, lines.join('\n'), 'text/markdown');
  };

  return (
    <>
      <PageHeader
        eyebrow={activeProject.name}
        title="Validation"
        subtitle="Live checks against the saved model text: required headers, numeric ranges, attack boxes, animations, asset references, and models.txt registration."
        actions={
          <>
            <Button icon={Download} onClick={downloadReport}>
              Download report
            </Button>
            <Button icon={Upload} onClick={() => openImport('into')}>
              Import files
            </Button>
          </>
        }
      />

      <div className="grid grid-4 stats-row" style={{ marginBottom: 14 }}>
        <div className="stat-card">
          <div className="stat-label"><AlertCircle /> Errors</div>
          <div className={validation.errors ? 'stat-value danger' : 'stat-value'}>{validation.errors}</div>
          <div className="stat-foot">Must be fixed before export</div>
        </div>
        <div className="stat-card">
          <div className="stat-label"><AlertTriangle /> Warnings</div>
          <div className="stat-value">{validation.warnings}</div>
          <div className="stat-foot">Review before exporting</div>
        </div>
        <div className="stat-card">
          <div className="stat-label"><Info /> Info</div>
          <div className="stat-value">{validation.infos}</div>
          <div className="stat-foot">Context and compatibility notes</div>
        </div>
        <div className="stat-card">
          <div className="stat-label"><FileCode2 /> Entities analysed</div>
          <div className="stat-value">{activeProject.entities.length}</div>
          <div className="stat-foot">{activeProject.modelsFile ? 'models.txt present' : 'models.txt missing'}</div>
        </div>
      </div>

      <Card style={{ marginBottom: 14 }}>
        <div className="card-body tight">
          <div className="row wrap" style={{ gap: 8, justifyContent: 'space-between' }}>
            <div className="segmented" role="group" aria-label="Filter validation severity">
              {(['all', 'error', 'warning', 'info'] as const).map((value) => (
                <button key={value} type="button" className={severity === value ? 'active' : ''} onClick={() => setSeverity(value)}>
                  {value === 'all' ? 'All' : value.charAt(0).toUpperCase() + value.slice(1)}
                </button>
              ))}
            </div>
            <div className="row wrap">
              <label className="sr-only" htmlFor="validation-entity">Filter by entity</label>
              <select
                id="validation-entity"
                className="select sm"
                value={entityFilter}
                onChange={(event) => setEntityFilter(event.target.value)}
                style={{ width: 210 }}
              >
                <option value="all">All entities</option>
                {activeProject.entities.map((entity) => (
                  <option key={entity.id} value={entity.id}>
                    {entity.summary.name ?? entity.fileName}
                  </option>
                ))}
              </select>
              <SearchInput value={query} onChange={setQuery} placeholder="Search findings…" width={230} />
              <Button
                size="sm"
                variant="ghost"
                onClick={() => {
                  setQuery('');
                  setSeverity('all');
                  setEntityFilter('all');
                }}
                disabled={!query && severity === 'all' && entityFilter === 'all'}
              >
                Clear
              </Button>
            </div>
          </div>
        </div>
      </Card>

      <div className="row-between" style={{ marginBottom: 10 }}>
        <div className="section-title" style={{ marginBottom: 0 }}>
          Findings <span className="count">{totalVisible}</span>
        </div>
        <span className="small muted">Validation runs on saved text. Use the editor's Validation tab for unsaved drafts.</span>
      </div>

      {validation.project.length > 0 && entityFilter === 'all' ? (
        <Card style={{ marginBottom: 14 }}>
          <div className="card-head">
            <div>
              <h3>Project-level findings</h3>
              <div className="sub">models.txt and cross-entity checks</div>
            </div>
            <Badge tone="warning">{validation.project.length}</Badge>
          </div>
          <div className="card-body col" style={{ gap: 7 }}>
            {validation.project
              .filter((finding) => severity === 'all' || finding.severity === severity)
              .map((finding, index) => (
                <FindingItem key={`project-${finding.code}-${index}`} finding={finding} />
              ))}
            {validation.project.filter((finding) => severity === 'all' || finding.severity === severity).length === 0 ? (
              <span className="small muted">No project-level findings for this filter.</span>
            ) : null}
          </div>
        </Card>
      ) : null}

      {findingsByEntity.length === 0 ? (
        <EmptyState
          icon={validation.errors + validation.warnings === 0 ? ShieldCheck : AlertCircle}
          title={
            severity === 'error'
              ? 'No errors'
              : severity === 'warning'
                ? 'No warnings'
                : validation.errors + validation.warnings === 0
                  ? 'No validation issues'
                  : 'No findings match these filters'
          }
          description={
            validation.errors + validation.warnings === 0
              ? 'All saved models pass the checks this app can perform. Export and test them in OpenBOR to verify runtime behaviour.'
              : 'Clear the filters to see the remaining findings.'
          }
        />
      ) : (
        <div className="col" style={{ gap: 14 }}>
          {findingsByEntity.map(({ entity, findings }) => (
            <EntityFindings key={entity.id} entity={entity} findings={findings} />
          ))}
        </div>
      )}
    </>
  );
}

function EntityFindings({ entity, findings }: { entity: ProjectEntity; findings: ValidationFinding[] }) {
  const errors = findings.filter((finding) => finding.severity === 'error').length;
  const warnings = findings.filter((finding) => finding.severity === 'warning').length;
  return (
    <Card>
      <div className="card-head">
        <div className="row" style={{ gap: 9 }}>
          <span className="entity-avatar">{(entity.summary.name ?? entity.fileName).slice(0, 2)}</span>
          <div>
            <h3>{entity.summary.name ?? entity.fileName}</h3>
            <div className="sub mono">{entity.path}</div>
          </div>
        </div>
        <div className="row wrap" style={{ gap: 5 }}>
          <Badge tone={typeTone(entity.summary.type)}>{typeLabel(entity.summary.type)}</Badge>
          {errors ? <Badge tone="error">{errors} errors</Badge> : null}
          {warnings ? <Badge tone="warning">{warnings} warnings</Badge> : null}
          <Button size="sm" variant="ghost" icon={FileCode2} onClick={() => navigate(`editor/${entity.id}`)}>
            Open editor
          </Button>
        </div>
      </div>
      <div className="card-body col" style={{ gap: 7 }}>
        {findings.map((finding, index) => (
          <FindingItem key={`${finding.code}-${finding.line}-${index}`} finding={finding} />
        ))}
      </div>
    </Card>
  );
}

function FindingItem({ finding }: { finding: ValidationFinding }) {
  return (
    <div className={`finding ${finding.severity}`}>
      <span className="finding-icon">
        {finding.severity === 'error' ? <AlertCircle size={14} /> : finding.severity === 'warning' ? <AlertTriangle size={14} /> : <Info size={14} />}
      </span>
      <div className="finding-body">
        <span className="finding-message">{finding.message}</span>
        <span className="finding-meta">
          <span>{finding.code}</span>
          {finding.line ? <span>line {finding.line}</span> : null}
          {finding.animation ? <span>{finding.animation}</span> : null}
          {finding.frame ? <span>frame {finding.frame}</span> : null}
        </span>
        {finding.detail ? <span className="finding-detail">{finding.detail}</span> : null}
        {finding.fix ? <span className="finding-fix">{finding.fix}</span> : null}
      </div>
    </div>
  );
}
